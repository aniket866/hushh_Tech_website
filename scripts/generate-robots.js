/**
 * Generates public/robots.txt.
 *
 * Two changes from the previous one-line "Allow: /":
 *
 * 1. Disallow rules. There were none, so onboarding flows, admin surfaces, per-user profiles and
 *    signed document views were all crawlable. Those pages have no search value and some show one
 *    person's data. The list mirrors NOINDEX_PREFIXES in api/seo/documentHead.js, which sets the
 *    matching X-Robots-Tag and meta robots.
 *
 * 2. Named AI crawlers, explicitly allowed. HushhTech publishes research it wants cited, so being
 *    read by answer engines is the point — and naming them makes that a decision on the record
 *    rather than a side effect of the wildcard.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const SITE_URL = "https://hushhtech.com";

// Keep in sync with NOINDEX_PREFIXES in api/seo/documentHead.js.
const DISALLOW = [
  "/onboarding/",
  "/hushh-user-profile",
  "/profile/",
  "/hushhid/",
  "/fund-admin",
  "/nda-admin",
  "/my-documents",
  "/document-viewer",
  "/sign-nda",
  "/reports/",
  "/deployments",
  "/metric",
  "/metrics",
  "/login",
  "/signup",
  "/signed-out",
  "/auth/",
  "/receipt-generator",
  "/delete-account",
];

// Answer engines and AI search crawlers we want to be readable by.
const AI_AGENTS = [
  "GPTBot",
  "OAI-SearchBot",
  "ChatGPT-User",
  "ClaudeBot",
  "Claude-User",
  "Claude-SearchBot",
  "PerplexityBot",
  "Perplexity-User",
  "Google-Extended",
  "Applebot-Extended",
  "CCBot",
  "Bingbot",
];

const disallowBlock = DISALLOW.map((rule) => `Disallow: ${rule}`).join("\n");

const robotsContent = `# HushhTech — https://hushhtech.com
# Generated by scripts/generate-robots.js. Do not edit by hand.

User-agent: *
Allow: /
${disallowBlock}

# HushhTech publishes research it wants cited. These crawlers are allowed on the
# same terms as any other: everything public, nothing behind the NDA gate.
${AI_AGENTS.map((agent) => `User-agent: ${agent}\nAllow: /\n${disallowBlock}\n`).join("\n")}
Sitemap: ${SITE_URL}/sitemap.xml
`;

fs.writeFileSync(path.join(__dirname, "../public/robots.txt"), robotsContent);
console.log(
  `✅ robots.txt generated — ${DISALLOW.length} disallow rules, ${AI_AGENTS.length} named AI agents`,
);
