#!/usr/bin/env node
/**
 * Turns content/decks/manifest.json into renderable community posts.
 *
 * Writes one DeckReader wrapper per deck plus a generated index that src/data/posts.ts spreads,
 * so adding a deck is a manifest edit and a re-run rather than hand-written React.
 *
 * Wrappers render the deck natively rather than embedding a gamma.app iframe. An iframe's content
 * belongs to the framed origin, so the deck page contributes no indexable text of its own — the
 * one page on this site that still does it delivers 33 characters of body text to a crawler. The
 * native render also survives a deck being edited or unshared, and it is readable on a phone.
 *
 * Usage: node scripts/community/generate-deck-posts.mjs
 */

import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const MANIFEST_PATH = join(root, "content/decks/manifest.json");
const TEXT_DIR = join(root, "content/decks/text");
const GATED_TEXT_DIR = join(root, "content/decks/text-gated");
const OUT_DIR = join(root, "src/content/posts/general/decks");

const GENERATED_HEADER = `// Generated by scripts/community/generate-deck-posts.mjs from content/decks/manifest.json.
// Do not edit by hand — re-run the generator instead.`;

const pascalCase = (value) =>
  value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const assetPrefixFor = (deck) =>
  deck.accessLevel === "NDA" ? `gated/decks/${deck.assetName}` : `decks/${deck.assetName}`;

/**
 * The first real paragraph of the extracted deck text is its own summary line, which makes a far
 * better card description and meta description than anything synthesised from the title.
 */
const descriptionFrom = (markdown, fallback) => {
  const paragraph = markdown
    .split("\n")
    .map((line) => line.trim())
    .find((line) => line && !line.startsWith("#") && line.length > 60);
  if (!paragraph) return fallback;
  const clean = paragraph.replace(/\s+/g, " ").trim();
  if (clean.length <= 200) return clean;
  const cut = clean.slice(0, 200);
  const lastStop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf("— "), cut.lastIndexOf(", "));
  return `${(lastStop > 120 ? cut.slice(0, lastStop) : cut).trim()}…`;
};

const wrapperSource = (deck, description) => {
  const component = pascalCase(deck.assetName);
  const prefix = assetPrefixFor(deck);
  return `${GENERATED_HEADER}
import React from "react";
import DeckReader from "../../../../components/community/DeckReader";

const ${component} = () => (
  <DeckReader
    title={${JSON.stringify(deck.title)}}
    description={${JSON.stringify(description)}}
    cardsSrc="/api/community/assets/${prefix}/cards.json"
    imageBaseSrc="/api/community/assets/${prefix}/pages"
    imagePageCount={${deck.pageCount}}
    cardCount={${deck.cardCount ?? deck.pageCount}}
    accessLevel={${JSON.stringify(deck.accessLevel)}}
    publishedAt={${JSON.stringify(deck.publishedAt)}}
    category={${JSON.stringify(deck.category)}}
  />
);

export default ${component};
`;
};

const indexSource = (entries) => {
  const imports = entries
    .map(({ component, deck }) => `import ${component} from './${deck.assetName}';`)
    .join("\n");

  const posts = entries
    .map(
      ({ component, deck, description }, index) => `  {
    count: ${500 + index},
    slug: '${deck.slug}',
    title: ${JSON.stringify(deck.title)},
    publishedAt: '${deck.publishedAt}',
    description: ${JSON.stringify(description)},
    category: ${JSON.stringify(deck.category)},
    Component: ${component},
    image: HushhAiLogoImg,
    accessLevel: '${deck.accessLevel}',
    sourceKind: 'deck',
    docFamily: ${JSON.stringify(deck.docFamily)},
    docVersion: ${deck.docVersion},
  },`,
    )
    .join("\n");

  return `${GENERATED_HEADER}
import HushhAiLogoImg from '../../../../components/images/blog2o.png';
import type { PostData } from '../../../../data/posts';
${imports}

export const deckPostList: PostData[] = [
${posts}
];

export default deckPostList;
`;
};

const main = async () => {
  const manifest = JSON.parse(await readFile(MANIFEST_PATH, "utf8"));
  // A deck is publishable once it has reading cards. Slide images are optional: ten of these were
  // published as a live Gamma embed and never had a page-image export, so they render Read-only.
  const publishable = manifest.decks.filter((deck) => Number(deck.cardCount) > 0 || Number(deck.pageCount) > 0);

  const skipped = manifest.decks.filter((deck) => !Number(deck.cardCount) && !Number(deck.pageCount));
  for (const deck of skipped) {
    console.warn(`skipping ${deck.slug}: no cards — run convert-gamma-export.mjs first`);
  }
  if (!publishable.length) {
    console.error("no decks have uploaded assets yet");
    process.exit(1);
  }

  // Regenerate from scratch so a deck removed from the manifest leaves no orphan wrapper behind.
  await rm(OUT_DIR, { recursive: true, force: true });
  await mkdir(OUT_DIR, { recursive: true });

  const entries = [];
  for (const deck of publishable) {
    let markdown = "";
    try {
      const textDir = deck.accessLevel === "NDA" ? GATED_TEXT_DIR : TEXT_DIR;
      markdown = await readFile(join(textDir, `${deck.assetName}.md`), "utf8");
    } catch {
      console.warn(`no extracted text for ${deck.slug} — description falls back to the title`);
    }
    // This repository is public and the manifest is committed, so an NDA deck must not carry an
    // auto-extracted description: those first paragraphs name the fund vehicle, its mandate size,
    // the audience the deck was prepared for, and per-position price targets. Set
    // publicDescription in the manifest to write a safe one by hand.
    const description =
      deck.accessLevel === "NDA"
        ? deck.publicDescription ||
          `${deck.title} — investor material, available once your NDA is approved.`
        : descriptionFrom(markdown, `${deck.title} — a HushhTech presentation.`);
    // Persist it so generate-community-snapshot.mjs, which builds the API copy straight from the
    // manifest, describes each deck the same way the rendered card does.
    deck.description = description;
    entries.push({ deck, description, component: pascalCase(deck.assetName) });
    await writeFile(join(OUT_DIR, `${deck.assetName}.tsx`), wrapperSource(deck, description));
  }

  await writeFile(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);

  // Newest first, matching how the community list orders.
  entries.sort((a, b) => b.deck.publishedAt.localeCompare(a.deck.publishedAt));
  await writeFile(join(OUT_DIR, "index.ts"), indexSource(entries));

  const written = await readdir(OUT_DIR);
  console.log(`generated ${entries.length} deck posts (${written.length} files) in ${OUT_DIR}`);
  console.log(
    `  ${entries.filter((e) => e.deck.accessLevel === "Public").length} Public, ` +
      `${entries.filter((e) => e.deck.accessLevel === "NDA").length} NDA`,
  );
};

main().catch((error) => {
  console.error(`generate-deck-posts: ${error.message}`);
  process.exit(1);
});
