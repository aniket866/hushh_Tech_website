import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export const DEFAULT_SOURCE_MANIFEST_PATH = path.join(
  "migration",
  "manifests",
  "supabase-retirement.v1.json"
);
export const DEFAULT_GENERATED_REGISTRY_PATH = path.join(
  "api",
  "shared",
  "supabaseRetirementFunctionRegistry.generated.js"
);

const REQUIRED_FIELDS = [
  "slug",
  "owner_group",
  "auth_mode",
  "migration_state",
  "final_disposition",
];

export const buildFunctionRegistryEntries = (manifest) => {
  if (!manifest || !Array.isArray(manifest.functions)) {
    throw new Error("Source manifest must contain a functions array.");
  }

  const entries = manifest.functions
    .map((entry) => ({
      slug: entry?.source?.slug,
      owner_group: entry?.owner_group,
      auth_mode: entry?.auth_mode,
      migration_state: entry?.migration_state,
      final_disposition: entry?.final_disposition,
    }))
    .sort((left, right) => left.slug.localeCompare(right.slug));

  const slugs = new Set();
  entries.forEach((entry, index) => {
    for (const field of REQUIRED_FIELDS) {
      if (typeof entry[field] !== "string" || entry[field].trim() === "") {
        throw new Error(`Function registry entry ${index} is missing ${field}.`);
      }
    }
    if (slugs.has(entry.slug)) {
      throw new Error(`Function registry contains duplicate slug ${entry.slug}.`);
    }
    slugs.add(entry.slug);
  });

  return entries;
};

export const digestFunctionRegistryEntries = (entries) =>
  crypto.createHash("sha256").update(JSON.stringify(entries), "utf8").digest("hex");

export const renderFunctionRegistry = (manifest) => {
  const entries = buildFunctionRegistryEntries(manifest);
  const digest = digestFunctionRegistryEntries(entries);
  const serialized = JSON.stringify(entries, null, 2);

  return `// Generated by scripts/ci/generate-supabase-retirement-function-registry.mjs.
// Do not edit this file by hand. Update the retirement manifest, then regenerate.

export const GCP_BACKEND_RETIREMENT_FUNCTION_REGISTRY_VERSION = 1;
export const GCP_BACKEND_RETIREMENT_FUNCTION_REGISTRY_DIGEST = "${digest}";

const registryEntries = ${serialized};

export const GCP_BACKEND_RETIREMENT_FUNCTIONS = Object.freeze(
  registryEntries.map((entry) => Object.freeze(entry))
);

export const GCP_BACKEND_RETIREMENT_FUNCTION_REGISTRY = Object.freeze(
  Object.fromEntries(
    GCP_BACKEND_RETIREMENT_FUNCTIONS.map((entry) => [entry.slug, entry])
  )
);
`;
};

export const checkGeneratedFunctionRegistry = ({
  manifestPath = DEFAULT_SOURCE_MANIFEST_PATH,
  generatedPath = DEFAULT_GENERATED_REGISTRY_PATH,
} = {}) => {
  const absoluteManifestPath = path.resolve(manifestPath);
  const absoluteGeneratedPath = path.resolve(generatedPath);
  const manifest = JSON.parse(fs.readFileSync(absoluteManifestPath, "utf8"));
  const entries = buildFunctionRegistryEntries(manifest);
  const expected = renderFunctionRegistry(manifest);
  const actual = fs.existsSync(absoluteGeneratedPath)
    ? fs.readFileSync(absoluteGeneratedPath, "utf8")
    : null;

  return {
    valid: actual === expected,
    manifestPath: absoluteManifestPath,
    generatedPath: absoluteGeneratedPath,
    functionCount: entries.length,
    digest: digestFunctionRegistryEntries(entries),
    error:
      actual === expected
        ? null
        : "Generated function registry is stale or missing. Run npm run migration:retirement:generate.",
  };
};

const parseArg = (name) => {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
};

const isDirectExecution =
  process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (isDirectExecution) {
  const manifestPath = parseArg("--manifest") || DEFAULT_SOURCE_MANIFEST_PATH;
  const generatedPath = parseArg("--output") || DEFAULT_GENERATED_REGISTRY_PATH;
  const write = process.argv.includes("--write");
  const manifest = JSON.parse(fs.readFileSync(path.resolve(manifestPath), "utf8"));
  const rendered = renderFunctionRegistry(manifest);

  if (write) {
    fs.mkdirSync(path.dirname(path.resolve(generatedPath)), { recursive: true });
    fs.writeFileSync(path.resolve(generatedPath), rendered);
    console.log(`Generated ${generatedPath}.`);
  } else {
    const result = checkGeneratedFunctionRegistry({ manifestPath, generatedPath });
    if (!result.valid) {
      console.error(`- ${result.error}`);
      process.exitCode = 1;
    } else {
      console.log(
        `Generated function registry valid: ${result.functionCount} functions, sha256 ${result.digest}.`
      );
    }
  }
}
